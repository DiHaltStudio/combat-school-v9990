"""ROM data of the two screens before the mission (src/mission_prelude.asm),
from assets/mission/prelude*.png and prelude.json (tools/extract_mission_prelude.py).

streams() returns the pictures as (label, bytes): per screen the background
and the atlas of its animated pictures, 4 bits per pixel, raw;
build_mission_visual.py packs them (tools/build_image_pack.py format,
upload_pack) and stores a picture once when screens share it (the
ending's mansion has the prelude mansion's pixels, in other colours). tables(locate)
returns the assembler tables; locate(label) gives (bank, address) of a
stream once build_mission_visual.py has placed it.

Per screen (prelude_<name>): black frames before, display frames (word),
black frames after, region count, palette address, picture table address,
colour-cycle address (0: none), background and atlas (bank, address).
Picture: atlas x, atlas row, width, height. Region: x, y, width, height,
runs address. Run: picture (255: background), dx, dy, frames; a region's
runs cover every display frame. Colour cycle: V9990 R, G, B (0..31) of
palette entry 15, frames.
"""
import json
from pathlib import Path
import numpy as np
from PIL import Image

ASSETS = Path('assets/mission')
SCREENS = (('attention', 57, 22), ('mansion', 22, 22), ('ending', 22, 3), ('intro', 0, 0))
MISSION = ('attention', 'mansion', 'ending')     # in the mission's banks
# 'intro' (the cartridge's introduction) is placed by tools/build_intro_anim.py.


def _rle(raw):
    out = bytearray()
    i = 0
    while i < len(raw):
        j = i + 1
        while j < len(raw) and raw[j] == raw[i] and j - i < 255:
            j += 1
        out += bytes((j - i, raw[i]))
        i = j
    return bytes(out + b'\0')


def _pack(idx):
    flat = idx.reshape(-1)
    return bytes(int(flat[i]) * 16 + int(flat[i + 1]) for i in range(0, len(flat), 2))


def _index(rgb, palette):
    P = np.array(palette, float)
    return ((rgb.reshape(-1, 1, 3).astype(float) - P[None]) ** 2).sum(2).argmin(1).reshape(rgb.shape[:2])


def _screen_atlas(data, name):
    """Pictures of one screen packed in rows of 256 pixels (tallest first).
    Opaque black, which would be transparent, uses the darkest other colour."""
    palette = data[name]['palette']
    darkest = 1 + min(range(15), key=lambda i: sum(palette[i + 1]))
    atlas = np.asarray(Image.open(ASSETS / 'prelude-pictures.png').convert('RGBA'))
    pics = [(i, p['box']) for i, p in enumerate(data['pictures']) if p['screen'] == name]
    pics.sort(key=lambda t: -t[1][3])
    boxes, x, y, row = {}, 0, 0, 0
    for i, (ax, ay, w, h) in pics:
        if x + w > 256:
            x, y, row = 0, y + row, 0
        boxes[i] = (x, y, w, h)
        x += w + (w & 1)
        row = max(row, h)
    height = (y + row + 1) & ~1
    out = np.zeros((height, 256), np.uint8)
    for i, (ax, ay, w, h) in pics:
        px, py, _, _ = boxes[i]
        part = atlas[ay:ay + h, ax:ax + w]
        idx = _index(part[..., :3], palette)
        idx[idx == 0] = darkest
        idx[part[..., 3] == 0] = 0
        out[py:py + h, px:px + w] = idx
    return out, boxes


def streams(names=MISSION):
    data = json.load(open(ASSETS / 'prelude.json'))
    result = []
    for name, _, _ in SCREENS:
        if name not in names:
            continue
        bg = np.asarray(Image.open(ASSETS / f'prelude-{name}.png').convert('RGB'))
        result.append((f'prelude_{name}_bg', _pack(_index(bg, data[name]['palette']))))
        atlas, _ = _screen_atlas(data, name)
        result.append((f'prelude_{name}_atlas', _pack(atlas)))
    return result


def tables(locate, names=None):
    data = json.load(open(ASSETS / 'prelude.json'))
    lines = ['; Generated by tools/mission_prelude_data.py.']
    for name, before, after in SCREENS:
        if names is not None and name not in names:
            continue
        s = data[name]
        _, boxes = _screen_atlas(data, name)
        bg_bank, bg_addr = locate(f'prelude_{name}_bg')
        at_bank, at_addr = locate(f'prelude_{name}_atlas')
        lines += [f'prelude_{name}:',
                  f'        db {before}',
                  f'        dw {s["frames"]}',
                  f'        db {after},{len(s["regions"])}',
                  f'        dw prelude_{name}_palette,prelude_{name}_pictures',
                  f'        dw {"prelude_" + name + "_cycle" if s["cycle"] else 0}',
                  f'        db {bg_bank}',
                  f'        dw 0x{bg_addr:04x}',
                  f'        db {at_bank}',
                  f'        dw 0x{at_addr:04x}']
        for k, r in enumerate(s['regions']):
            x, y, w, h = r['box']
            lines.append(f'        db {x},{y},{w},{h}')
            lines.append(f'        dw prelude_{name}_runs{k}')
        lines.append(f'prelude_{name}_palette:')
        lines.append('        db ' + ','.join(str(v >> 3) for c in s['palette'] for v in c))
        index = {i: n for n, i in enumerate(sorted(boxes))}
        lines.append(f'prelude_{name}_pictures:')
        for i in sorted(boxes):
            lines.append('        db ' + ','.join(map(str, boxes[i])))
        for k, r in enumerate(s['regions']):
            lines.append(f'prelude_{name}_runs{k}:')
            for pic, dx, dy, n in r['runs']:
                lines.append(f'        db {255 if pic < 0 else index[pic]},{dx},{dy},{n}')
        if s['cycle']:
            lines.append(f'prelude_{name}_cycle:')
            for rgb, n in s['cycle']:
                lines.append('        db ' + ','.join(str(v >> 3) for v in rgb) + f',{n}')
    return '\n'.join(lines) + '\n'
