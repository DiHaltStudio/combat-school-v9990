#!/usr/bin/env python3
"""Extract provisional arcade-derived Step 3 art from supplied video frames.

Frames are generated by extract_step3_reference.sh; outputs are project assets
and the original video is not needed for normal builds. Masks are approximate
because the recording is scaled/compressed, not native MAME graphics data.
"""
from pathlib import Path
import argparse
from PIL import Image, ImageDraw

source = Path('build/step3-reference')
out = Path('assets/step3')
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--mine-reference',type=Path,help='Screenshot of the arcade mine explosion')
parser.add_argument('--fall-reference',type=Path,help='Screenshot of the arcade seated fall')
parser.add_argument('--bridge-reference',type=Path,help='Screenshot showing the arcade bridge')
args=parser.parse_args()
out.mkdir(parents=True, exist_ok=True)
ground = Image.open(source/'02.png').convert('RGB')
ground_next = Image.open(source/'06.png').convert('RGB')
water = Image.open(source/'24.png').convert('RGB')
water_swim = Image.open(source/'18.png').convert('RGB')
finish = Image.open(source/'38.png').convert('RGB')

ground.crop((385,750,505,870)).resize((24,24),Image.Resampling.LANCZOS).save(out/'sand.png')
ground.crop((185,605,300,835)).resize((22,44),Image.Resampling.LANCZOS).save(out/'bush.png')
ground.crop((495,420,680,515)).resize((28,14),Image.Resampling.LANCZOS).save(out/'puddle.png')
ground_next.crop((930,240,1265,425)).resize((48,27),Image.Resampling.LANCZOS).save(out/'rocks.png')
if args.bridge_reference:
    bridge=Image.open(args.bridge_reference).convert('RGB')
    # The right-hand bridge is unoccupied in the chosen reference frame.
    bridge.crop((930,70,1240,405)).resize((58,70),Image.Resampling.LANCZOS).save(out/'bridge.png')
# Use a clear section of river, avoiding the dark vertical camera separator.
water_swim.crop((205,350,335,610)).resize((24,48),Image.Resampling.LANCZOS).save(out/'water.png')

def runner(name, frame, box):
    image = frame.crop(box).convert('RGBA')
    w,h = image.size
    # Mask captures the top-down silhouette, retaining skin and shirt details.
    mask = Image.new('L',(w,h))
    draw = ImageDraw.Draw(mask)
    def polygon(coords):
        draw.polygon([(int(x*w),int(y*h)) for x,y in coords],fill=255)
    polygon(((.32,.02),(.65,.02),(.75,.14),(.72,.23),(.9,.30),(1,.39),
             (.95,.46),(.76,.41),(.7,.58),(.65,.70),(.55,.75),(.5,.97),
             (.34,.99),(.32,.74),(.24,.62),(.25,.42),(.05,.46),(0,.37),
             (.1,.28),(.28,.22),(.25,.12)))
    # Let colour segmentation recover the whole trouser/foot silhouette instead
    # of cutting it with the upper-body polygon.
    draw.rectangle((0,int(h*.55),w,h),fill=255)
    image.putalpha(mask)
    # Sand visible between the legs belongs to the background, not the runner.
    # Keep the dark green trouser pixels and skin-coloured arms above the waist.
    pixels = image.load()
    for y in range(int(h*.55),h):
        for x in range(w):
            r,g,b,a = pixels[x,y]
            if a and not (g > r*.87 and g > b*1.04 and g < 165):
                pixels[x,y] = (r,g,b,0)
    image.resize((24,32),Image.Resampling.LANCZOS).save(out/name)

runner('runner-player.png',ground,(525,530,660,735))
runner('runner-cpu.png',ground,(1010,530,1150,725))
runner('runner-player-2.png',ground_next,(555,530,715,720))
runner('runner-cpu-2.png',ground_next,(1075,440,1245,650))
# Additional consecutive running poses from the MAME recording, sampled by
# tools/extract_step3_run_frames.sh. These files are committed as assets.
sequence=Path('build/step3-run-reference')
if (sequence/'01.png').exists() and (sequence/'03.png').exists():
    runner('runner-player-3.png',Image.open(sequence/'01.png').convert('RGB'),(510,530,660,735))
    runner('runner-player-4.png',Image.open(sequence/'03.png').convert('RGB'),(520,530,670,735))
# At the finish the arcade runner stands with both feet visible. The white
# result caption overlaps the lower edge, so exclude bright caption pixels.
standing = finish.crop((360,240,485,435)).convert('RGBA')
w,h=standing.size
mask=Image.new('L',(w,h))
md=ImageDraw.Draw(mask)
md.polygon([(int(x*w),int(y*h)) for x,y in (
    (.30,.02),(.68,.02),(.75,.17),(.88,.22),(.98,.36),(.9,.51),
    (.76,.48),(.75,.70),(.68,.97),(.53,.99),(.49,.79),(.45,.99),
    (.30,.97),(.25,.70),(.24,.48),(.10,.51),(.02,.36),(.12,.22),(.25,.17))],fill=255)
standing.putalpha(mask)
pixels=standing.load()
for y in range(h):
    for x in range(w):
        r,g,b,a=pixels[x,y]
        if a and ((r>200 and g>200 and b>180) or (y>h*.53 and not (g>r*.87 and g>b*1.04 and g<165))):
            pixels[x,y]=(r,g,b,0)
standing.resize((24,32),Image.Resampling.LANCZOS).save(out/'runner-standing.png')
# Keep a common head anchor between the two manually isolated running frames.
for prefix in ('runner-player','runner-cpu'):
    first=Image.open(out/(prefix+'.png')).convert('RGBA')
    second=Image.open(out/(prefix+'-2.png')).convert('RGBA')
    second.paste(first.crop((7,0,17,8)),(7,0))
    second.save(out/(prefix+'-2.png'))
    if prefix == 'runner-player':
        for suffix in ('-3','-4'):
            path=out/(prefix+suffix+'.png')
            if path.exists():
                frame=Image.open(path).convert('RGBA')
                frame.paste(first.crop((7,0,17,8)),(7,0))
                frame.save(path)

def water_object(name, frame, box):
    image = frame.crop(box).convert('RGBA')
    data=[]
    for r,g,b,a in image.getdata():
        # Keep pale spray/foam while making the surrounding teal transparent.
        is_foam = r>105 and g>145 and b>140
        is_water = g>r*1.45 and b>r*1.15 and g>80 and not is_foam
        data.append((r,g,b,0 if is_water else 255))
    image.putdata(data)
    image.resize((24,32),Image.Resampling.LANCZOS).save(out/name)

water_object('swimmer-cpu.png',water_swim,(415,205,570,455))
water_object('swimmer-player.png',water_swim,(530,450,690,700))
water_object('boat-player.png',water,(555,465,700,765))
if args.mine_reference:
    explosion=Image.open(args.mine_reference).convert('RGBA').crop((455,525,570,690))
    data=[]
    for r,g,b,a in explosion.getdata():
        # Isolate pale smoke/debris and dark fragments against the sand.
        pale=r>145 and g>145 and b>140 and abs(r-g)<38
        dark=max(r,g,b)<100 and abs(r-g)<30
        data.append((r,g,b,255 if pale or dark else 0))
    explosion.putdata(data)
    explosion.resize((16,16),Image.Resampling.LANCZOS).save(out/'mine-blast.png')
if args.fall_reference:
    fallen=Image.open(args.fall_reference).convert('RGBA').crop((535,575,690,715))
    w,h=fallen.size
    mask=Image.new('L',(w,h))
    ImageDraw.Draw(mask).polygon([(int(x*w),int(y*h)) for x,y in (
        (.28,.18),(.45,.06),(.65,.03),(.78,.18),(.78,.35),(.95,.65),
        (1,.78),(.80,.78),(.72,.95),(.30,.95),(.18,.78),(0,.78),
        (.05,.64),(.22,.37))],fill=255)
    fallen.putalpha(mask)
    fallen.resize((24,32),Image.Resampling.LANCZOS).save(out/'runner-fallen.png')
