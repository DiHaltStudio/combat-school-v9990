#!/usr/bin/env python3
"""Arcade songs arranged for the PSG (../musicPsg/notas/*.json, written by
../musicPsg/tools/arreglo_arcade.py) for the player of src/psg_arcade.asm.

Writes build/psg/arcade.bin (the bank of the cartridge that holds them,
tools/build_megarom.py) and build/psg/arcade.inc (constants).

Bank layout, at 8000h: the song count, then per song its offset (from
8000h) and length, two words each; then the songs. A song is a list of
notes in time order, starting with a note: each note is two bytes, channel
(bits 7-6; 3: no note) with the note number - 24 (bits 5-0), and its
key-on length in ticks (50 Hz); after each note one byte, the ticks until
the next one (0-249), or 254 (the loop starts here: read on), 253 (back to
the loop) or 255 (the end). A wait over 249 ticks is split with an empty
note (channel 3).

The tone periods of notes 24-87 (64 words, MSX clock) and the volume
envelope are tables of src/psg_arcade.asm (arcade-periods.inc here)."""
import json
from pathlib import Path

SRC = Path(__file__).resolve().parents[2] / 'musicPsg' / 'notas'
OUT = Path('build/psg')
# Song numbers of psg_arcade (src/psg_calls.asm), in this order.
SONGS = ('12_mansion_final_arreglo', '13_tus_grados_arreglo', '15_ranking_arreglo',
         '16_game_over_arreglo', '17_sargento_arreglo', '18_dominadas_arreglo',
         '19_cadetes_corriendo_arreglo', '20_wicked_child_msx')
ZX, MSX = 1773400, 1789773
LOW = 24                       # note number of period index 0


def song_bytes(d):
    notes = sorted((s, ay, n, ln) for s, ay, n, ln, _ in d['notes'])
    out = bytearray((0xC0, 0))          # starts with a (empty) note
    now = 0
    loop = d['loop_tick']
    marked = loop is None
    def wait_to(t):
        nonlocal now, marked
        while True:
            if not marked and loop <= t:
                gap = loop - now
                while gap > 249:
                    out.extend((249, 0xC0, 0)); gap -= 249; now += 249
                out.append(gap); out.extend((0xC0, 0)); now = loop
                out.append(254)
                marked = True
            gap = t - now
            if gap <= 249:
                return gap
            out.extend((249, 0xC0, 0)); now += 249
    for s, ay, n, ln in notes:
        gap = wait_to(s)
        n = min(max(n, LOW), LOW + 63)
        out.extend((gap, ay << 6 | (n - LOW), min(ln, 255)))
        now = s
    gap = wait_to(d['ticks'])
    out.extend((gap, 0xC0, 0))
    out.append(253 if loop is not None else 255)
    return bytes(out)


def periods():
    """Period of notes 24..87 on the MSX: the Spectrum driver's (as the
    arrangement chose it), scaled to the MSX clock, else equal-tempered."""
    table = {}
    for f in SRC.glob('*.json'):
        for n, p in json.load(open(f))['periods'].items():
            table[int(n)] = p
    out = []
    for n in range(LOW, LOW + 64):
        p = round(table[n] * MSX / ZX) if n in table else round(MSX / (16 * 440 * 2 ** ((n - 69) / 12)))
        out.append(min(p, 4095))
    return out


songs = [song_bytes(json.load(open(SRC / f'{name}.json'))) for name in SONGS]
bank = bytearray([len(songs)])
offset = 1 + 4 * len(songs)
for s in songs:
    bank += bytes((offset & 255, (offset >> 8) + 0x80, len(s) & 255, len(s) >> 8))
    offset += len(s)
for s in songs:
    bank += s
assert len(bank) <= 0x4000
OUT.mkdir(parents=True, exist_ok=True)
(OUT / 'arcade.bin').write_bytes(bank)
env = json.load(open(SRC / f'{SONGS[0]}.json'))
p = periods()
(OUT / 'arcade.inc').write_text(
    '; Generated by tools/build_psg_arcade.py.\n'
    f'ARC_BANK equ 26              ; arcade.bin in the cartridge (tools/build_megarom.py)\n'
    f'ARC_SONGS equ {len(songs)}\n'
    f'ARC_BIGGEST equ {max(len(s) for s in songs)}\n'
    'arc_periods:\n' + ''.join(f'        dw {",".join(map(str, p[i:i + 8]))}\n' for i in range(0, 64, 8)) +
    'arc_envelope:                  ; key on: levels per tick, then arc_sustain\n'
    f'        db {",".join(map(str, env["env"]))}\n'
    f'ARC_ENV_LEN equ {len(env["env"])}\n'
    f'ARC_SUSTAIN equ {env["sustain"]}\n'
    'arc_release:                   ; after the key off, at most these levels\n'
    f'        db {",".join(map(str, env["release"]))}\n'
    f'ARC_REL_LEN equ {len(env["release"])}\n')
print('arcade songs:', ', '.join(f'{n} {len(s)} B' for n, s in zip(SONGS, songs)), f'; bank {len(bank)} B')
