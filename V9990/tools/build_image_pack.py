#!/usr/bin/env python3
"""Compressed full-screen pictures of bank 0 (intro_frame in src/demo_b1.asm).

The race background, the title and intro frames, the Step 4 and Step 6
bonus, the Step 6 interlude and the bonus tables and map used to be stored
raw, two banks each. Readers: intro_frame (src/demo_b1.asm),
transition_screen (src/step3_transition.asm) and map_screen (src/penalty.asm). They are now RLE streams packed from bank FIRST_BANK. Control
byte: 1..127 literal bytes follow (sent with OTIR, as fast as the raw
upload), 129..255 the next byte repeated (control - 128) times, 128 the
stream continues at the start of the next bank (the last byte of every
bank a stream uses is that marker), 0 end.
Callers still name a picture by its old first bank (its key).

Some pictures carried extra data in the padding of their second bank
(read at 0xAA00): the bonus arrow markers (6 x 72 bytes) and the two
interlude poses (2 x 1248 bytes). Each is kept within one bank; intro_frame
leaves its bank and address in C0C8..C0CA.

Writes build/demo/image-pack.bin (whole banks) and image-table.inc:
image_table: key, bank, stream address, extra bank, extra address (7 bytes
per picture), ended by key 0.
"""
from pathlib import Path

p = Path('build/demo')
B = 0x4000
FIRST_BANK = 19
SIZE = 27136                     # 256 x 212 pixels, 4 bits per pixel

def raw_pictures():
    """(key, 32 KiB block) for every picture, as the raw layout had them."""
    out = [(1, (p / 'image.bin').read_bytes() + bytes([0xff]) * (0x8000 - SIZE))]
    intro = (p / 'intro.bin').read_bytes()
    # The title (19). The introduction's 15 frames (21..49) are gone: the
    # introduction is now drawn at the arcade's frame rate
    # (tools/build_intro_anim.py, bank 53).
    out.append((19, intro[0:0x8000]))
    out.append((51, (p / 'step6-bonus-compact.bin').read_bytes()))
    out.append((53, (p / 'step6-interlude.bin').read_bytes()))
    out.append((83, (p / 'step4-bonus-compact.bin').read_bytes()))
    progress = (p / 'progress-compact.bin').read_bytes()
    for i, k in enumerate((58, 60, 62)):
        out.append((k, progress[i * 0x8000:(i + 1) * 0x8000]))
    return out

# Extra data read after the picture: progress_marker, transition_marker
# (src/step3_transition.asm), step6_interlude_patch.
EXTRA = {51: 6 * 104, 58: 6 * 104, 60: 6 * 104, 83: 6 * 104, 53: 2 * 1248}   # markers: 8 rows x 13 bytes

# Shorter runs go out faster as literals (OTIR) than as a repeat unit; 12
# keeps every picture within one intro frame (200 ms), as fast as raw data.
MIN_REPEAT = 12

def units(raw):
    """(literal bytes) or (count, value) units of the stream."""
    out, lit, i = [], bytearray(), 0
    while i < len(raw):
        j = i + 1
        while j < len(raw) and raw[j] == raw[i] and j - i < 127:
            j += 1
        if j - i >= MIN_REPEAT:
            if lit:
                out.append(bytes(lit)); lit = bytearray()
            out.append((j - i, raw[i]))
        else:
            lit += raw[i:j]
        i = j
    if lit:
        out.append(bytes(lit))
    return out

def encode(raw, start):
    """The stream for absolute pack offset `start`. A unit never takes the
    last byte of a bank: that byte is always the 128 marker, so the decoder
    only changes bank at a marker. Literal runs are split to fit."""
    out = bytearray()
    def room():
        return B - (start + len(out)) % B
    def next_bank():
        out.append(128)
        out.extend(bytes([0xff]) * (room() % B))
    for u in units(raw):
        if isinstance(u, tuple):
            if room() < 3:
                next_bank()
            out += bytes((128 + u[0], u[1]))
            continue
        while u:
            if room() < 3:
                next_bank()
            n = min(len(u), 127, room() - 2)
            out.append(n)
            out += u[:n]
            u = u[n:]
    if room() < 2:
        next_bank()
    out.append(0)
    return bytes(out)

if __name__ == '__main__':
    pack = bytearray()
    table = []
    pictures = raw_pictures()
    for key, block in pictures:
        start = len(pack)
        if B - start % B < 3:
            pack += bytes([0xff]) * (B - start % B)
            start = len(pack)
        pack += encode(block[:SIZE], start)
        table.append([key, FIRST_BANK + start // B, 0x8000 + start % B, 0, 0])
    # Extras after all the streams, never across a bank boundary.
    for entry in table:
        key = entry[0]
        if key not in EXTRA:
            continue
        data = dict(pictures)[key][SIZE:SIZE + EXTRA[key]]
        if len(pack) % B + len(data) > B:
            pack += bytes([0xff]) * (-len(pack) % B)
        entry[3:] = [FIRST_BANK + len(pack) // B, 0x8000 + len(pack) % B]
        pack += data
    pack += bytes([0xff]) * (-len(pack) % B)
    (p / 'image-pack.bin').write_bytes(pack)
    lines = ['; Generated by tools/build_image_pack.py.',
             f'IMAGE_PACK_BANKS equ {len(pack) // B}', 'image_table:']
    for key, bank, addr, xbank, xaddr in table:
        lines.append(f'        db {key},{bank}')
        lines.append(f'        dw 0x{addr:04x}')
        lines.append(f'        db {xbank}')
        lines.append(f'        dw 0x{xaddr:04x}')
    lines.append('        db 0')
    (p / 'image-table.inc').write_text('\n'.join(lines) + '\n')
    print(f'{len(pictures)} pictures in {len(pack) // B} banks from bank {FIRST_BANK} '
          f'(raw: {2 * len(pictures)} banks)')
