#!/usr/bin/env python3
"""The mission's music (the Spectrum's song 8) as register writes, so the
mission plays it without the Spectrum driver (src/mission_boss.asm
mission_music_tick): a tick of the driver takes 1.1..2.3 ms, reading one of
these about 0.12 ms.

Source: ../musicPsg/regs/08_castigo_y_mision.txt, the driver's registers
tick by tick (50 Hz), 1601 ticks, the loop from tick 321. R11..R13 are never
used by this song: only R0..R10. Tone periods scaled to the MSX PSG clock,
R7 bits 7-6 = 10 (the MSX PSG I/O ports), as tools/build_psg_music.py.

Each tick: a 16-bit mask (bit n = Rn changes), then the new values in
register order. The first tick and the loop's first tick have every
register. A mask of FFFFh ends: play again from MISSION_MUSIC_LOOP.

build/psg/mission-music.bin goes to bank 26 at 9000h (after the arcade
songs, tools/build_megarom.py); build/psg/mission-music.inc."""
from pathlib import Path

SRC = Path('../musicPsg/regs/08_castigo_y_mision.txt')
OUT = Path('build/psg')
BANK, ADDR = 26, 0x9000          # page 2, after the arcade songs (bank 26, 4 KiB)
REGS = 11

head = SRC.read_text().splitlines()[0]
loop_tick = int(head.split('loop_tick=')[1].split()[0])
rows = [[int(v, 16) for v in l.split()[:14]] for l in SRC.read_text().splitlines()
        if l.strip() and not l.startswith('#')]
assert all(r[11:14] == [0, 0, 0] for r in rows)


def msx(r):
    r = list(r[:REGS])
    for c in range(3):
        p = r[2 * c] | (r[2 * c + 1] & 15) << 8
        p = min(4095, round(p * 1789773 / 1773400))
        r[2 * c], r[2 * c + 1] = p & 255, p >> 8
    r[7] = (r[7] & 0x3F) | 0x80
    return r


data = bytearray()
loop_offset = None
shown = None
for t, row in enumerate(map(msx, rows)):
    if t == loop_tick:
        loop_offset = len(data)
        shown = None
    mask = 0
    for i in range(REGS):
        if shown is None or row[i] != shown[i]:
            mask |= 1 << i
    data += bytes((mask & 255, mask >> 8))
    data += bytes(row[i] for i in range(REGS) if mask >> i & 1)
    shown = row
data += b'\xff\xff'
assert ADDR - 0x8000 + len(data) <= 0x4000

OUT.mkdir(parents=True, exist_ok=True)
(OUT / 'mission-music.bin').write_bytes(data)
(OUT / 'mission-music.inc').write_text(f'''; Generated by tools/build_mission_music.py: the Spectrum's song 8 as
; register writes ({len(rows)} ticks, the loop from tick {loop_tick}).
MISSION_MUSIC_BANK equ {BANK}
MISSION_MUSIC equ 0x{ADDR:04x}
MISSION_MUSIC_LOOP equ 0x{ADDR + loop_offset:04x}
''')
print(f'mission music: {len(data)} bytes, {len(rows)} ticks, loop at tick {loop_tick}')
