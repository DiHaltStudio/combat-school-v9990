#!/usr/bin/env python3
"""The arcade's running cadets after the Iron-Man bonus (src/step3_transition.asm,
transition_animation): background, palette, pose atlas and actor table.

Inputs (from the arcade, see tools/extract_cadets.py):
  assets/step3-transition/background.png  the barracks, 256x212
  assets/step3-transition/cadets.png      15 poses of 32x48: cadet, sergeant, player
  assets/step3-transition/cadets.json     cycles and actors of the scene
Outputs in build/step3: transition-bg.bin (two banks), transition-atlas.bin
(one bank; 256x96 used), transition-palette.bin and cadets.inc.
"""
import json
import sys
from pathlib import Path
from PIL import Image
sys.path.insert(0, str(Path(__file__).resolve().parent))

out = Path('build/step3'); out.mkdir(parents=True, exist_ok=True)
src = Path('assets/step3-transition')
bg = Image.open(src / 'background.png').convert('RGB')
atlas = Image.open(src / 'cadets.png').convert('RGBA')
scene = json.loads((src / 'cadets.json').read_text())

# One fixed palette of exact arcade colours for the background (13 colours)
# and the actors (21): the closest ones share a pen. Black is pen 0
# (transparent for the blitter).
colors = [(0, 0, 0),
          (90, 148, 231),   # 1 sky
          (115, 99, 82),    # 2 ground; also its speckle and the darkest flesh
          (33, 33, 33),     # 3 shadows of the barracks and trees
          (66, 90, 115),    # 4 roofs
          (90, 90, 90),     # 5 grey: walls, the cadets' vests
          (132, 132, 156),  # 6 light walls
          (33, 66, 33),     # 7 dark green: trousers, trees
          (66, 66, 41),     # 8 olive
          (74, 107, 0),     # 9 green: trousers, the sergeant's shirt
          (214, 140, 123),  # 10 skin
          (198, 165, 132),  # 11 light skin
          (198, 90, 0),     # 12 player shirt
          (255, 132, 33),   # 13 light orange
          (140, 148, 107),  # 14 the sergeant's light green
          (239, 239, 239)]  # 15 white
WEIGHT = (2, 4, 3)
# The trees' greens would turn olive: keep them green.
TREES = {(49, 74, 49): 7, (66, 99, 82): 7}


def idx(im, first=0):
    """Nearest pen of each pixel (weighted RGB), from pen `first`: 1 for the
    actors, whose pen 0 is transparent."""
    rgb = im.convert('RGB')
    cache = {}
    def pen(c):
        if c in TREES:
            return TREES[c]
        if c not in cache:
            cache[c] = min(range(first, 16), key=lambda i: sum(w * (c[j] - colors[i][j]) ** 2 for j, w in enumerate(WEIGHT)))
        return cache[c]
    out = Image.new('P', rgb.size)
    out.putdata([pen(c) for c in rgb.getdata()])
    return out


def pack(im):
    p = list(im.getdata())
    return bytes(p[i] * 16 + p[i + 1] for i in range(0, len(p), 2))


field = pack(idx(bg))
(out / 'transition-bg.bin').write_bytes(field + bytes(32768 - len(field)))
cells = Image.new('P', (256, 128), 0)
cells.paste(idx(atlas, 1), (0, 0), atlas.getchannel('A').point(lambda a: 255 if a >= 128 else 0))
(out / 'transition-atlas.bin').write_bytes(pack(cells))
(out / 'transition-palette.bin').write_bytes(bytes(v >> 3 for rgb in colors for v in rgb))
preview = cells.copy(); preview.putpalette([c for rgb in colors for c in rgb] + [0] * (768 - 48))
preview.save(out / 'transition-atlas-preview.png')

# cadets.inc: the actors for the Z80. Times are arcade frames (60 Hz).
kinds = list(scene['kinds'])
lines = ['; Generated by tools/build_step3_transition.py from assets/step3-transition/cadets.json.',
         f'CADET_FRAMES equ {scene["frames"]}      ; the scene, in arcade frames (60 Hz)',
         f'CADET_ACTORS equ {len(scene["actors"])}',
         '; Per kind: frames of a whole cycle of six poses, x speed in half pixels',
         '; per frame, then the six atlas cells (eight 32x48 cells per row).',
         'cadet_kinds:']
for k in kinds:
    d = scene['kinds'][k]
    lines.append(f'        db {d["cycle_frames"]},{d["speed_half_px"]},' + ','.join(map(str, d['cycle'])) + f'   ; {k}')
lines += ['; Per actor, back to front (8 bytes): first frame (word), x at that frame',
          '; (signed word, pixels), screen row, kind, and at frame 0 its cycle state:',
          '; accumulator (6 per frame, a pose step at each cycle length) and pose.',
          'cadet_actors:']
for a in scene['actors']:
    period = scene['kinds'][a['kind']]['cycle_frames']
    acc, pose = 6 * a['offset'] % period, 6 * a['offset'] // period % 6
    lines.append(f'        dw {a["start"]},{a["x"]}\n        db {a["y"]},{kinds.index(a["kind"])},{acc},{pose}   ; {a["kind"]}')
(out / 'cadets.inc').write_text('\n'.join(lines) + '\n')
print('transition palette:', colors)
