#!/usr/bin/env python3
"""The cartridge's player-versus-CPU introduction at the arcade's frame rate
(src/demo_b1.asm show_intro, src/intro_slide.asm), from the 'intro' screen of
tools/extract_mission_prelude.py (make capture-intro-full).

Arcade frames (60 Hz) after the start button: 370..376 black; 377..410 both
portraits side by side at the bottom; 411..447 NICK's moves up 3 pixels per
frame; 448..490 it moves right 3 pixels per frame, to its place above JOE's;
491..793 the two small runners and the typed names (the region engine,
src/mission_prelude.asm); then the race.

Writes build/demo/intro-anim.inc: the region engine (its VRAM rows moved to
2944 and 3160, clear of Step 1's graphics), the screen's tables and
intro_slide_path (NICK's portrait x, y per frame, 377..490, screen rows =
arcade rows - 2); and build/demo/intro-anim.bin, the pictures from bank
FIRST_BANK (tools/build_image_pack.py format).
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import mission_prelude_data as m
import build_image_pack as bip

FIRST_BANK = 53
B = 0x4000
out = Path('build/demo')

bip.MIN_REPEAT = 3
pack, where = bytearray(), {}
for label, data in m.streams(('intro',)):
    if B - len(pack) % B < 3:
        pack += bytes([0xff]) * (B - len(pack) % B)
    where[label] = (FIRST_BANK + len(pack) // B, 0x8000 + len(pack) % B)
    pack += bip.encode(data, len(pack))
pack += bytes([0xff]) * (-len(pack) % B)
(out / 'intro-anim.bin').write_bytes(pack)

# NICK's portrait: its blue area's top-left in the arcade, per frame.
path = []
for n in range(377, 491):
    if n <= 410:
        x, y = 3, 113
    elif n <= 447:
        x, y = 3, max(3, 113 - 3 * (n - 410))
    else:
        x, y = min(132, 6 + 3 * (n - 449)) if n >= 449 else 3, 3
    path.append((x - 1, y - 2 - 1))      # the portrait's frame, screen rows

engine = Path('src/mission_prelude.asm').read_text()
start = engine.index('mission_prelude:')
end = engine.index('; HL = screen (see tools/mission_prelude_data.py).')
engine = engine[:start] + engine[end:]
for old, new in (('PRE_BASE_ROW equ 512', 'PRE_BASE_ROW equ 2944'),
                 ('PRE_ATLAS_ROW equ 768', 'PRE_ATLAS_ROW equ 3160')):
    assert engine.count(old) == 1, old
    engine = engine.replace(old, new)
lines = ['; Generated by tools/build_intro_anim.py.',
         'raw_command equ command',
         engine,
         m.tables(where.__getitem__, ('intro',)),
         f'INTRO_SLIDE_FRAMES equ {len(path)}',
         'intro_slide_path:']
lines += ['        db ' + ','.join(f'{x},{y}' for x, y in path[i:i + 8]) for i in range(0, len(path), 8)]
(out / 'intro-anim.inc').write_text('\n'.join(lines) + '\n')
print(f'intro: {len(pack) // B} banks from {FIRST_BANK}, path {len(path)} frames')
