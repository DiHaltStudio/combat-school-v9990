"""Data of the RANKING table and the arcade ending text screens (src/ranking.asm), from
assets/mission/ending-font.png and ending.json (tools/extract_mission_ending.py)
and the arcade program ROM 611g01 (texts at 0x55a3..0x5760, default
RANKING table at 0x565e).

source() returns the assembler data: the font as two RLE streams (glyph
pixels, then shadow pixels; 32 glyphs per 8-pixel row, 256 x 16), the
palette, the colour cycle of the RANKING title, the screens' texts and the
default RANKING table.

Text lists: x cell, y pixel, colour, glyphs..., 255; the list ends with
x = 255. Glyph 254 is a space. Colours (palette entries): 0 black,
1 shadow, 2..12 fixed text colours, 13 the RANKING title cycle, 14 the
blinking rank on the officer screen.
"""
import json
from pathlib import Path
import numpy as np
from PIL import Image
from mission_prelude_data import _rle, _pack

ASSETS = Path('assets/mission')
SPACE = 254
COLOURS = [(0, 0, 0), (33, 33, 33),
           (239, 0, 99), (247, 140, 0), (239, 239, 0), (156, 247, 0), (0, 198, 0),
           (0, 247, 156), (0, 189, 247), (0, 123, 255), (0, 0, 222), (156, 0, 239),
           (239, 239, 239), (239, 239, 239), (0, 189, 247), (0, 0, 0)]
PINK, CYAN, WHITE, CYCLE, BLINK = 2, 8, 12, 13, 14
ROW_COLOURS = range(2, 12)          # 1ST pink .. 10TH purple
# Officer ranks, highest first: score strictly over the threshold.
THRESHOLDS = (370000, 340000, 300000, 260000, 240000, 220000, 200000)
# Arcade titles of the RANKING table (9 cells from column 23), by rank.
TITLES = ('   CP.   ', '  F.LT.  ', '  S.LT.  ', '  M.SGT. ', '   SGT.  ',
          '   CPL.  ', '   PRT.  ', '  ROOKIE ')
# Initial ranking names, in order; scores and titles keep the arcade defaults.
DEFAULTS = ((225000, 'CTM', 5), (214800, 'FGG', 6), (200010, 'MDM', 6),
            (184100, 'ETM', 7), (160760, 'FTM', 7), (88500, 'RTM', 7),
            (58100, 'MSV', 7), (44600, 'IAS', 7), (31330, 'PGG', 7),
            (29980, 'MSX', 7))
# Officer screen: the 8 ranks from cell row 2, 3 rows apart.
RANK_NAMES = (('CAPTAIN',), ('FIRST', 'LIEUTENANT'), ('SECOND', 'LIEUTENANT'),
              ('MASTER', 'SERGEANT'), ('SERGEANT',), ('CORPORAL',), ('PRIVATE',),
              ('ROOKIE',))


def _glyphs():
    return json.load(open(ASSETS / 'ending.json'))['glyphs']


def encode(text):
    g = _glyphs()
    return [SPACE if c == ' ' else g.index(c) for c in text]


def row_y(row):
    """Cell row to pixel row: the arcade's 28 rows in 212 lines; the last
    two (the player's score) move up 12 lines."""
    return row * 8 if row < 26 else row * 8 - 12


def _line(x, row, colour, text):
    return f'        db {x},{row_y(row)},{colour},' + ','.join(map(str, encode(text))) + ',255'


def _font():
    img = np.asarray(Image.open(ASSETS / 'ending-font.png').convert('RGB')).astype(int)
    n = img.shape[1] // 8
    fg = np.zeros((16, 256), np.uint8)
    sh = np.zeros((16, 256), np.uint8)
    for g in range(n):
        cell = img[:, g * 8:g * 8 + 8]
        y, x = (g // 32) * 8, (g % 32) * 8
        fg[y:y + 8, x:x + 8] = np.where(cell[..., 0] == 239, 15, 0)
        sh[y:y + 8, x:x + 8] = np.where(cell[..., 0] == 33, 1, 0)
    return _rle(_pack(fg)), _rle(_pack(sh))


def _db(data, per=24):
    return '\n'.join('        db ' + ','.join(map(str, data[i:i + per])) for i in range(0, len(data), per))


def source():
    data = json.load(open(ASSETS / 'ending.json'))
    g = data['glyphs']
    fg, sh = _font()
    out = ['; Generated by tools/mission_ending_data.py.',
           f'END_G0 equ {g.index("0")}',
           f'END_GSPACE equ {SPACE}',
           f'END_GDOT equ {g.index(".")}',
           f'END_RANKS equ {len(THRESHOLDS) + 1}',
           'end_font_fg:', _db(list(fg)),
           'end_font_shadow:', _db(list(sh)),
           'end_palette:', _db([v >> 3 for c in COLOURS for v in c]),
           # RANKING title: palette entry 13, one colour per 4 frames.
           f'END_CYCLE_LEN equ {len(data["title_cycle"])}',
           'end_title_cycle:', _db([v >> 3 for c in data['title_cycle'] for v in c]),
           'end_blink:', _db([v >> 3 for c in data['blink'] for v in c])]
    # Thresholds, 24-bit little-endian, highest first.
    out.append('end_thresholds:')
    out.append(_db([b for t in THRESHOLDS for b in t.to_bytes(3, 'little')]))
    # Officer screen: fixed texts, then per rank its lines (for the blink).
    out.append('end_rank_texts:')
    out.append(_line(12, 0, PINK, 'YOUR  TITLE'))
    # Without the arcade's P1 (NICK) and score of rows 26..27 (user).
    out.append('        db 255')
    out.append('end_rank_blocks:')
    out.append('        dw ' + ','.join(f'end_rank_block{i}' for i in range(len(RANK_NAMES))))
    for i, names in enumerate(RANK_NAMES):
        row = 2 + 3 * i
        out.append(f'end_rank_block{i}:')
        if i < 3:
            out.append(_line(7, row, CYAN, 'OVER'))
            out.append(_line(11, row + 1, CYAN, f'{THRESHOLDS[i]}PTS'))
        for k, name in enumerate(names):
            out.append(_line(21, row + k, CYAN, name))
        out.append('        db 255')
    out.append('end_rank_rows:')
    out.append(_db([row_y(2 + 3 * i) for i in range(len(RANK_NAMES))]))
    out.append('end_arrow:')
    out.append(_db(encode('1P>') + [255]))
    out.append('end_congrats_texts:')
    out.append(_line(8, 10, PINK, 'CONGRATULATIONS!'))
    out.append(_line(5, 13, PINK, 'THANK YOU FOR PLAYING'))
    out.append('        db 255')
    out.append('end_ranking_texts:')
    out.append(_line(13, 3, CYCLE, 'RANKING'))
    out.append(_line(2, 5, WHITE, 'RANK    SCORE   NAME   TITLE'))
    labels = ('1ST', '2ND', '3RD', '4TH', '5TH', '6TH', '7TH', '8TH', '9TH', '10TH')
    for i, label in enumerate(labels):
        out.append(_line(6 - len(label), 7 + 2 * i, ROW_COLOURS[i], label))
    out.append('        db 255')
    out.append('end_ranking_colours:')
    out.append(_db(list(ROW_COLOURS)))
    # Initials: A..Z, space, '.', '!', '?' and END (the last one).
    chars = encode('ABCDEFGHIJKLMNOPQRSTUVWXYZ') + [SPACE] + encode('.!?#')
    out.append(f'END_NAME_CHARS equ {len(chars)}')
    out.append('end_name_chars:')
    out.append(_db(chars))
    out.append('end_titles:')
    out.append(_db([x for t in TITLES for x in encode(t)]))
    # Default table: score (24-bit), name (3 glyphs), title.
    out.append('end_defaults:')
    out.append(_db([b for s, n, t in DEFAULTS for b in list(s.to_bytes(3, 'little')) + encode(n) + [t]], 21))
    return '\n'.join(out) + '\n'
